"""Narration: finds every say("...") line in the GDScript sources and renders a voice clip
for it with espeak-ng, in the voice of whoever is talking. Clips are named by
md5("v<VOICE_VERSION>|<mood>|<text>")[:12] - the same key the game computes at runtime
(Narrator.key_for)."""
import glob
import hashlib
import os
import re

import numpy as np

import synth as S

MOODS = {"CUTE": 0, "DARK": 1, "WHISPER": 2, "CRITTER": 3, "CREEPY": 4, "HYPE": 5, "CHUMBO": 6, "ROCKO": 7,
         "MONSTER": 8, "HONK": 9, "PIP": 10, "TAXMAN": 11, "SARGE": 12, "HYPE_DARK": 13}

STR = r'"((?:[^"\\]|\\.)*)"'
SAY_RE = re.compile(r"\bsay(?:_bg)?\(\s*" + STR + r"\s*(?:,\s*Narrator\.(\w+))?")
PAIR_RE = re.compile(r"\[\s*" + STR + r"\s*,\s*Narrator\.(\w+)\s*\]")

# How the words should be pronounced (display text keeps the funny spellings).
SAY_AS = [
    (r"\bpokemans\b", "pokey mans"), (r"\bpokémans\b", "pokey mans"), (r"\broblocks\b", "row blocks"),
    (r"\bchumbmon\b", "chumb mon"), (r"\bobby\b", "obbie"), (r"\bbaaa\b", "baaaa"), (r"\bshh\b", "shhh"),
    (r"\bi'm chumbo\b", "I'm chumbo"),
    (r"\bdiji(mon|volve|vice|egg)", r"dih jee \1"), (r"\bblobmon\b", "blob mon"), (r"\bpartymon\b", "party mon"),
    (r"\bfrostmon\b", "frost mon"), (r"\bgrrthdaymon\b", "grrrth day mon"), (r"\bcakemon\b", "cake mon"),
    (r"\bchumbomon\b", "chumbo mon"), (r"\buab\b", "you ay bee"),
]


def unescape(s):
    return s.encode().decode("unicode_escape") if "\\" in s else s


def find_lines(root):
    found = {}
    for path in glob.glob(os.path.join(root, "scripts", "**", "*.gd"), recursive=True):
        src = open(path, encoding="utf-8").read()
        for m in SAY_RE.finditer(src):
            text, mood = unescape(m.group(1)), m.group(2) or "CUTE"
            if "%" not in text:
                found[(MOODS[mood], text)] = path
        for m in PAIR_RE.finditer(src):
            text, mood = unescape(m.group(1)), m.group(2)
            if "%" not in text:
                found[(MOODS[mood], text)] = path
    return found


def lines_by_script(root):
    """{res:// script path: [voice keys in source order]} so a game can decode its lines up front."""
    out = {}
    for path in sorted(glob.glob(os.path.join(root, "scripts", "**", "*.gd"), recursive=True)):
        src = open(path, encoding="utf-8").read()
        hits = []
        for rx, has_default in ((SAY_RE, True), (PAIR_RE, False)):
            for m in rx.finditer(src):
                text = unescape(m.group(1))
                mood = m.group(2) or "CUTE"
                if "%" not in text:
                    hits.append((m.start(), key_for(MOODS[mood], text)))
        keys = []
        for _, k in sorted(hits):
            if k not in keys:
                keys.append(k)
        if keys:
            res = "res://" + os.path.relpath(path, root).replace(os.sep, "/")
            out[res] = keys
    return out


def write_index(root):
    idx = lines_by_script(root)
    lines = ["# AUTO-GENERATED by tools/build_audio.py - do not edit.", "extends RefCounted", "",
             "## Narration clips each script can play, in source order.", "const BY_SCRIPT := {"]
    for path in sorted(idx):
        keys = ", ".join('"%s"' % k for k in idx[path])
        lines.append(f'\t"{path}": [{keys}],')
    lines.append("}")
    with open(os.path.join(root, "scripts", "gen", "voice_index.gd"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


# Bumped when every clip is re-recorded, so the new files get new names (nothing old can be
# picked up from an import cache or a browser cache). Must match Narrator.VOICE_VERSION.
VOICE_VERSION = 3


def key_for(mood, text):
    return hashlib.md5(f"v{VOICE_VERSION}|{mood}|{text}".encode("utf-8")).hexdigest()[:12]


def tts_text(text):
    t = text.lower()
    for pat, rep in SAY_AS:
        t = re.sub(pat, rep, t)
    t = re.sub(r"\bi\b", "I", t)
    return t


# Every character always speaks with exactly the same voice. The party host and the announcer
# have two each - a good one and an evil one - and every one of their spooky lines uses the evil
# one, so there are never more than those two.
CHARACTERS = {
    "host": dict(timbre="lady", pitch=178, speed=152, range=120),
    "host_evil": dict(timbre="deep", pitch=64, speed=118, range=28),
    "announcer": dict(timbre="guy", pitch=128, speed=178, range=130),
    "announcer_evil": dict(timbre="guy", pitch=84, speed=132, range=40),
    "sarge": dict(timbre="deep", pitch=100, speed=172, range=100),
    "chumbo": dict(timbre="guy", pitch=108, speed=158, range=45),
    "diji": dict(timbre="kid", pitch=320, speed=175, range=110),
    "honk": dict(timbre="goose", pitch=150, speed=185, range=110),
    "pip": dict(timbre="kid_whisper", pitch=260, speed=125, range=50),
    "taxman": dict(timbre="deep", pitch=84, speed=142, range=35),
}

# Narrator mood -> whose voice
MOOD_VOICE = {0: "host", 1: "host_evil", 2: "host_evil", 3: "diji", 4: "everyone", 5: "announcer", 6: "chumbo",
              7: "rocko", 8: "diji", 9: "honk", 10: "pip", 11: "taxman", 12: "sarge", 13: "announcer_evil"}


def _base(who, t):
    c = CHARACTERS[who]
    return S.speak(t, c["timbre"], c["pitch"], c["speed"], c["range"])


def _mix(*parts):
    n = max(len(p) + int(d * S.SR) for p, _, d in parts)
    out = np.zeros(n)
    for x, gain, delay in parts:
        j = int(delay * S.SR)
        out[j:j + len(x)] += x * gain
    return out


def voice(who, text):
    """One line of speech in a character's voice: (dry samples, with its room sound)."""
    t = tts_text(text)
    if who == "everyone":
        # all the party guests saying it together, slow and flat
        a = S.speak(t, "lady", 150, 108, 12)
        b = S.speak(t, "guy", 96, 108, 8)
        c = S.speak(t, "kid", 250, 108, 12)
        d = S.speak(t, "whisper", 120, 108, 8)
        x = _mix((a, 0.7, 0.0), (b, 0.8, 0.025), (c, 0.45, 0.05), (d, 0.5, 0.012))
        return x, S.reverb(x, 0.45, 1.4)
    if who == "rocko":
        # the demon cat (growl + whisper, slowed down)
        a = S.speak(t, "croak", 56, 118, 12)
        b = S.speak(t, "whisper", 112, 118, 12)
        n = max(len(a), len(b))
        a = np.pad(a, (0, n - len(a)))
        b = np.pad(b, (0, n - len(b)))
        tt = np.arange(n) / S.SR
        x = np.tanh(a * (0.7 + 0.3 * np.sin(2 * np.pi * 29 * tt)) * 2.5) * 0.7 + b * 0.45
        x = S.lp(S.resample(x, 1.1), 3800)
        return x, S.reverb(x, 0.45, 1.5)
    x = _base(who, t)
    if who == "host_evil":
        # slow, low and smooth, in a big dark room
        x = S.lp(S.resample(x, 1.08), 4200)
        return x, S.reverb(x, 0.35, 1.3)
    if who == "announcer_evil":
        # the same stadium PA, slowed down and broken, echoing round an empty arena
        x = np.tanh(S.bp(S.resample(x, 1.05), 220, 3600) * 2.2) * 0.8
        return x, S.reverb(x, 0.35, 1.6)
    if who == "diji":
        x = S.resample(x, 1 / 1.12)
    elif who == "honk":
        x = S.resample(S.bp(x, 380, 3800), 1 / 1.06)
    elif who == "sarge":
        # barking through a megaphone
        x = np.tanh(S.bp(x, 300, 3600) * 2.5) * 0.8
    elif who == "taxman":
        # on a little TV screen in the truck
        x = S.bp(x, 280, 3400) * 1.4
    room = {"host": (0.12, 0.6), "pip": (0.5, 1.4), "sarge": (0.12, 0.5)}.get(who, (0.1, 0.5))
    return x, S.reverb(x, *room)


def render(mood, text):
    x, y = voice(MOOD_VOICE[mood], text)
    y = np.asarray(y)
    if y.ndim == 2:
        y = y.mean(axis=0)
    # trim the reverb tail a bit and fade
    tail = int(0.35 * S.SR)
    y = y[: len(x) + tail]
    f = min(len(y), int(0.08 * S.SR))
    y[-f:] *= np.linspace(1, 0, f)
    return y


def build(root, force=False):
    out_dir = os.path.join(root, "assets", "voice")
    os.makedirs(out_dir, exist_ok=True)
    lines = find_lines(root)
    keep = set()
    made = 0
    for (mood, text) in sorted(lines):
        k = key_for(mood, text)
        keep.add(k + ".ogg")
        path = os.path.join(out_dir, k + ".ogg")
        if os.path.exists(path) and not force:
            continue
        y = render(mood, text)
        y = y / (np.max(np.abs(y)) + 1e-9) * 0.9
        S.write_ogg_mono(path, y, quality=1)
        made += 1
    removed = 0
    for f in os.listdir(out_dir):
        if f.endswith(".ogg") and f not in keep:
            os.remove(os.path.join(out_dir, f))
            imp = os.path.join(out_dir, f + ".import")
            if os.path.exists(imp):
                os.remove(imp)
            removed += 1
    write_index(root)
    print(f"  voice: {len(lines)} lines ({made} new, {removed} removed)")
